export function helpForSection(
  section: number,
  decision?: string,
  hasErrors = false,
) {
  const ids =
    decision === "ADDITIONAL_DATA_REQUIRED"
      ? ["missing", "csv", "validation"]
      : decision
        ? ["decision", "terms", "csv"]
        : section === 0
          ? ["company", "csv"]
          : section === 1
            ? ["csv", "coverage"]
            : section === 2
              ? ["obligations", "csv"]
              : section === 3
                ? ["forecast", "csv"]
                : ["terms", "csv"];
  if (hasErrors && !ids.includes("validation")) ids.push("validation");
  return ids.map((id) => applicationHelp.find((x) => x.id === id)!);
}
export function referenceAnswer(
  id: string,
  a: MvpApplication,
  section: number,
): string | null {
  const help = applicationHelp.find(
    (x) => x.id === id && (x.sections.includes(section) || a.decision),
  );
  if (!help) return null;
  let text = help.template;
  if (id === "terms") {
    const q = a.questionnaire,
      p = products.find((x) => x.id === q.productId);
    text =
      q.amount > 0
        ? `Сохранённый запрос: ${p?.name ?? "Продукт не выбран"}, ${q.amount.toLocaleString("ru-RU")} ₽, ${q.term} мес. Ставка каталога ${p?.rate ?? "не указана"}%. Это не одобрение. ` +
          text
        : help.missing;
  }
  if (id === "missing")
    text = a.missing.length
      ? text + "\n\n" + a.missing.map((x) => "• " + x.label).join("\n")
      : help.missing;
  if (id === "decision") {
    const labels = {
      APPROVED:
        "Кредит одобрен. Следующий шаг — договор и подпись, затем получение средств.",
      MANAGER_REVIEW_REQUIRED:
        "Предварительная оценка положительная, требуется окончательное решение менеджера. Запишитесь на встречу.",
      ADDITIONAL_DATA_REQUIRED:
        "Для решения нужны дополнительные сведения. Дополните указанные поля и выписки.",
      DECLINED:
        "Запрошенные условия не прошли проверку. Доступны только пересчитанные варианты, показанные в результате.",
    };
    text = a.decision
      ? labels[a.decision] + "\n\n" + a.reasons.slice(0, 3).join("\n")
      : help.missing;
  }
  return (
    text +
    "\n\nИсточник: " +
    help.source +
    ". Это справка, не новое решение по кредиту."
  );
}
