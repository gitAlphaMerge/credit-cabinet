export function industryFromOkved(code = "") {
  if (!code) return "Не определена";
  const n = Number(code.split(".")[0]);
  return n <= 3
    ? "Сельское хозяйство"
    : n >= 10 && n <= 33
      ? "Производство"
      : n >= 41 && n <= 43
        ? "Строительство"
        : n >= 45 && n <= 47
          ? "Торговля и маркетплейсы"
          : n >= 49 && n <= 53
            ? "Логистика и транспорт"
            : n === 56
              ? "Общепит"
              : n >= 62 && n <= 63
                ? "IT"
                : "Услуги";
}
