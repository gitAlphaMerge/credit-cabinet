// Run with playwright-cli run-code --filename=scripts/check-chat-redesign.cjs.
// Uses only temporary server 4174, never the main user database.
// prettier-ignore
async page => {
  const base = "http://localhost:4174";
  if (!page.url().startsWith(base)) throw new Error("Only use the isolated test server");
  const check = (ok, message) => { if (!ok) throw new Error(message); };
  const runtimeErrors = [];
  page.on("pageerror", error => runtimeErrors.push(error.message));
  const state = async () => (await page.request.get(base + "/api/state")).json();
  const screenshot = async name => { await page.waitForTimeout(250); return page.screenshot({ path: "output/playwright/chat-v3-" + name + ".png" }); };
  const field = () => page.getByRole("textbox", { name: "Сообщение финансовому помощнику", exact: true });
  const setup = await page.request.post(base + "/api/auth/register", { data: { phone: "+7" + String(Date.now()).slice(-10), password: "Chat-test-1710", profile: { name: "ООО «Проверка чата»", form: "ООО", registered: true, stage: "operating", sector: "Производство", ageBand: "3–5 лет", result: "Прибыль", debt: "Нет", intent: "Подобрать финансирование" } } });
  check(setup.ok(), "Registration setup failed");
  await page.request.patch(base + "/api/preferences", { data: { tourDone: true } });
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto(base + "/chat");
  await page.getByRole("heading", { name: "Чем помочь вашему бизнесу?" }).waitFor();
  check(await page.locator(".starter-prompts button").count() === 3, "Wrong number of starter actions");
  check(await page.locator(".composer-row").evaluate(el => parseFloat(getComputedStyle(el).borderRadius)) >= 25, "Composer is not capsule shaped");
  await screenshot("empty");
  await page.getByRole("button", { name: "Скрыть историю", exact: true }).click();
  await page.waitForTimeout(250);
  check(await page.locator(".chat-history").getAttribute("inert") !== null, "Hidden history remains interactive");
  await screenshot("history-collapsed");
  await page.getByRole("button", { name: "Открыть историю", exact: true }).click();
  await page.route("**/api/chats/*/messages", async route => { await new Promise(resolve => setTimeout(resolve, 250)); await route.continue(); });
  await page.locator(".starter-prompts").getByRole("button", { name: "Какие документы нужны?", exact: true }).dblclick();
  await page.locator(".message.assistant").first().waitFor();
  await page.waitForFunction(() => !document.querySelector(".thinking"));
  await page.unroute("**/api/chats/*/messages");
  let current = (await state()).chats[0];
  check(current.messages.length === 2, "Quick Action double click sent duplicate messages");
  await field().fill("Первая строка");
  await field().press("Shift+Enter");
  await field().pressSequentially("Вторая строка");
  check((await field().inputValue()).includes("\n"), "Shift+Enter did not insert a newline");
  await field().press("Enter");
  await page.waitForFunction(() => document.querySelectorAll(".message.assistant").length === 2 && !document.querySelector(".thinking"));
  check((await state()).chats[0].messages.length === 4, "Enter did not send exactly once");
  await screenshot("messages");
  await page.getByRole("button", { name: /Переименовать текущий диалог:/ }).click();
  await page.getByRole("textbox", { name: "Название диалога", exact: true }).fill("Закупка оборудования · расчёт");
  await page.getByRole("button", { name: "Сохранить", exact: true }).click();
  await page.getByRole("button", { name: "Поиск по истории", exact: true }).click();
  await page.getByRole("textbox", { name: "Поиск диалогов", exact: true }).fill(" ЗАКУПКА ");
  check(await page.locator(".history-select").count() === 1, "Search does not trim or ignore case");
  await page.getByRole("textbox", { name: "Поиск диалогов", exact: true }).fill("не существует");
  await page.getByText("Нет диалогов по этому запросу", { exact: true }).waitFor();
  await screenshot("history-search");
  await page.getByRole("button", { name: "Очистить поиск", exact: true }).click();
  await page.locator(".history-new").click();
  await page.getByRole("heading", { name: "Чем помочь вашему бизнесу?" }).waitFor();
  check((await state()).chats.length === 2, "New dialog not stored");
  await page.getByRole("button", { name: "Переименовать диалог: Новый диалог", exact: true }).click();
  await page.getByRole("textbox", { name: "Название диалога", exact: true }).fill("Запасы");
  await page.getByRole("button", { name: "Сохранить", exact: true }).click();
  await page.locator(".history-select").filter({ hasText: "Закупка оборудования" }).click();
  check(await page.locator(".message.assistant").count() === 2, "Opening old dialog lost its messages");
  const selectionResponse = await page.request.post(base + "/api/selections", { data: { purpose: "Оборудование", amount: 6500000, term: 36, flow: 120000, existing: 20000, ownFunds: 0, repayFrom: "Выручка" } });
  check(selectionResponse.ok(), "Could not save financial selection");
  const selection = await selectionResponse.json();
  const linkedResponse = await page.request.post(base + "/api/chats", { data: { selectionId: selection.id } });
  check(linkedResponse.ok(), "Could not create linked chat");
  const linked = await linkedResponse.json();
  await page.reload();
  await page.locator(".starter-prompts").getByRole("button", { name: "Объясни мой последний расчёт", exact: true }).click();
  await page.locator(".message .calculation").waitFor();
  await page.locator(".message .calculation > details > summary").click();
  check(await page.locator(".message .calculation tbody tr").count() === 36, "Full payment schedule lost");
  await page.locator(".chat-finance-warning").waitFor();
  await page.getByRole("button", { name: "Скрыть историю", exact: true }).click();
  await page.locator(".messages").evaluate(el => el.scrollTop = 0);
  await screenshot("calculation");
  const longDraft = Array.from({ length: 14 }, (_, i) => `Строка ${i + 1}: хочу уточнить параметры финансирования.`).join("\n");
  await field().fill(longDraft);
  await page.waitForTimeout(300);
  check(Math.round((await field().boundingBox()).height) === 180, "Composer not capped at 180px");
  await page.locator(".composer input[type=file]").setInputFiles("fixtures/statement.csv");
  await page.getByRole("dialog", { name: "Проверьте извлечённые данные" }).waitFor();
  await page.getByRole("button", { name: "Подтвердить и сохранить", exact: true }).click();
  await page.locator(".toast").getByRole("button").click();
  await page.locator(".composer-file").filter({ hasText: "Данные подтверждены" }).waitFor();
  check((await state()).documents.length === 1, "Document was not stored once");
  await screenshot("composer-document");
  await page.getByRole("button", { name: "Совмещённый режим", exact: true }).click();
  await page.locator(".split-chat .chat-v3").waitFor();
  check(await field().inputValue() === longDraft, "Draft lost in split mode");
  check(await page.locator(".composer-file").count() === 1, "File chip lost in split mode");
  check((await page.locator(".split-chat").boundingBox()).width / (await page.locator(".split-workspace").boundingBox()).width < .43, "Initial chat is not near 40 percent");
  await screenshot("split");
  await page.getByRole("separator").focus();
  await page.getByRole("separator").press("ArrowRight");
  await page.getByRole("button", { name: "Открыть чат отдельной страницей", exact: true }).click();
  check(await field().inputValue() === longDraft, "Draft lost returning to full chat");
  await page.getByRole("button", { name: "Совмещённый режим", exact: true }).click();
  await page.getByRole("button", { name: "Скрыть чат", exact: true }).click();
  check(await page.locator(".split-chat").count() === 0, "Chat did not close");
  await page.getByRole("button", { name: "Показать чат", exact: true }).click();
  check(await field().inputValue() === longDraft, "Draft lost on close/restore");
  await page.getByRole("button", { name: "Открыть чат отдельной страницей", exact: true }).click();
  await field().fill("");
  for (const [width, height] of [[1920,1080], [1440,900], [1366,768], [1100,800], [768,1024], [390,844]]) {
    await page.setViewportSize({ width, height });
    await page.waitForTimeout(250);
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth && scrollY === 0), "Page overflow " + width);
    const composer = await page.locator(".composer-row").boundingBox();
    check(composer.x >= 0 && composer.x + composer.width <= width && composer.y + composer.height <= height, "Composer outside viewport " + width);
    check((await page.locator(".chat-thread").boundingBox()).width <= 825, "Reading column too wide");
    if (width === 390 || width === 1366) await screenshot("full-" + width);
  }
  await page.getByRole("button", { name: "Открыть историю", exact: true }).click();
  await page.getByRole("dialog", { name: "История диалогов", exact: true }).waitFor();
  check(await page.locator(".chat-main").getAttribute("inert") !== null, "Mobile drawer does not isolate main content");
  await screenshot("mobile-history");
  await page.getByRole("dialog", { name: "История диалогов" }).press("Escape");
  await page.waitForTimeout(250);
  check(await page.locator(".chat-main").getAttribute("inert") === null, "Mobile drawer left main inert");
  for (const [width, height] of [[1440,900], [1100,800], [768,1024], [390,844]]) {
    await page.setViewportSize({ width, height });
    await page.getByRole("button", { name: "Совмещённый режим", exact: true }).click();
    if (width < 1100) await page.locator(".mobile-work-tabs").getByRole("button", { name: "Чат", exact: true }).click();
    await page.locator(".split-chat .chat-v3").waitFor();
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "Split overflow " + width);
    const pane = await page.locator(".split-chat").boundingBox();
    const composer = await page.locator(".composer-row").boundingBox();
    const send = await page.getByRole("button", { name: "Отправить сообщение", exact: true }).boundingBox();
    check(composer.x >= pane.x && composer.x + composer.width <= pane.x + pane.width && send.x + send.width <= pane.x + pane.width, "Split Composer clipped " + width);
    if (width === 390 || width === 1100) await screenshot("split-" + width);
    await page.getByRole("button", { name: "Открыть чат отдельной страницей", exact: true }).click();
  }
  await page.getByRole("button", { name: "Скрыть плашку statement.csv", exact: true }).click();
  check((await state()).documents.length === 1, "Hiding file chip deleted document");
  check((await state()).chats.find(c => c.id === linked.id).messages.length === 2, "Mode changes modified conversation");
  await page.emulateMedia({ reducedMotion: "reduce" });
  check(await page.locator(".chat-thread").evaluate(el => getComputedStyle(el).animationName) === "none", "Reduced motion ignored");
  check(runtimeErrors.length === 0, "Uncaught browser errors: " + runtimeErrors.join("; "));
}
