// playwright-cli run-code --filename=scripts/check-motion.cjs; isolated server 4174.
// prettier-ignore
async page => {
  const base = "http://localhost:4174";
  if (!page.url().startsWith(base)) throw new Error("Only use isolated test server 4174");
  const check = (value, text) => { if (!value) throw new Error(text); };
  const errors = [];
  page.on("pageerror", e => errors.push(e.message));
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto(base + "/");
  await page.mouse.move(0, 0);
  await page.waitForFunction(() => document.querySelector(".finance-theatre")?.dataset.playing === "true");
  const initial = await page.locator(".finance-scene-card").getAttribute("data-scene");
  await page.waitForFunction(i => document.querySelector(".finance-scene-card")?.dataset.scene !== i, initial, { timeout: 7500 });
  await page.getByRole("button", { name: "Приостановить анимацию", exact: true }).click();
  const paused = await page.locator(".finance-scene-card").getAttribute("data-scene");
  await page.mouse.move(0, 0);
  await page.waitForTimeout(5100);
  check(await page.locator(".finance-scene-card").getAttribute("data-scene") === paused, "Pause failed");
  await page.getByRole("button", { name: "03 Прогноз", exact: true }).click();
  check(await page.locator(".finance-scene-card").getAttribute("data-scene") === "2", "Manual scene failed");
  await page.screenshot({ path: "output/playwright/motion-hero-desktop.png" });
  await page.locator("#how").scrollIntoViewIfNeeded();
  await page.waitForFunction(() => document.querySelectorAll(".journey-step.revealed").length === 3);
  check(await page.locator(".finance-theatre").getAttribute("data-playing") === "false", "Offscreen theatre keeps cycling");
  await page.waitForTimeout(1000);
  await page.screenshot({ path: "output/playwright/motion-steps.png" });
  for (const width of [390, 768, 1440, 1920]) {
    await page.setViewportSize({ width, height: 900 });
    await page.evaluate(() => scrollTo(0, 0));
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "Landing overflow " + width);
    const r = await page.locator(".finance-controls").boundingBox();
    check(r.x >= 0 && r.x + r.width <= width, "Controls overflow " + width);
    if (width === 390) await page.screenshot({ path: "output/playwright/motion-hero-mobile.png", fullPage: true });
  }
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.getByRole("button", { name: "Подобрать финансирование", exact: true }).first().click();
  await page.getByText("Бизнес уже работает", { exact: true }).click();
  await page.getByRole("button", { name: "Продолжить", exact: true }).click();
  await page.getByText("ООО", { exact: true }).click();
  await page.getByRole("combobox").selectOption("Производство");
  await page.getByText("3–5 лет", { exact: true }).click();
  await page.getByRole("button", { name: "Продолжить", exact: true }).click();
  await page.getByText("Прибыль", { exact: true }).click();
  await page.getByText("Нет", { exact: true }).click();
  await page.getByText("Подобрать финансирование", { exact: true }).click();
  await page.getByRole("button", { name: "Продолжить", exact: true }).click();
  const phone = "+7" + String(Date.now()).slice(-10), password = "Motion-test-1710";
  await page.getByRole("textbox", { name: "Номер телефона", exact: true }).fill(phone);
  await page.getByLabel("Пароль", { exact: true }).fill(password);
  const submit = page.locator(".auth-form button[type=submit], .auth-form > button.button");
  await page.route("**/api/auth/register", route => route.fulfill({ status: 503, contentType: "application/json", body: JSON.stringify({ error: "Проверка ошибки регистрации" }) }));
  await submit.click();
  await page.getByRole("alert").getByText("Проверка ошибки регистрации", { exact: true }).waitFor();
  check(await page.locator(".preparation-screen").count() === 0, "Animation started before successful registration");
  await page.unroute("**/api/auth/register");
  await submit.click();
  await page.getByRole("progressbar", { name: "Подготовка кабинета", exact: true }).waitFor();
  const start = Date.now();
  await page.waitForFunction(() => Number(document.querySelector(".preparation-sphere")?.getAttribute("aria-valuenow")) >= 30);
  await page.screenshot({ path: "output/playwright/motion-preparation-desktop.png" });
  const saved = await (await page.request.get(base + "/api/state")).json();
  check(saved.profile.sector === "Производство" && saved.credit === null, "Registration data not saved");
  await page.reload();
  await page.getByRole("progressbar", { name: "Подготовка кабинета", exact: true }).waitFor();
  await page.waitForFunction(() => Number(document.querySelector(".preparation-sphere")?.getAttribute("aria-valuenow")) >= 25);
  const resumed = Number(await page.getByRole("progressbar").getAttribute("aria-valuenow"));
  await page.waitForURL(base + "/cabinet", { timeout: 11000 });
  check(Date.now() - start >= 9000 && Date.now() - start < 12500, "Not a 10 second transition");
  check(resumed >= 25, "Preparation did not resume");
  await page.getByRole("dialog").getByRole("button", { name: "Пропустить" }).click();
  await page.getByRole("button", { name: "Выйти", exact: true }).click();
  await page.goto(base + "/login");
  await page.getByRole("textbox", { name: "Номер телефона", exact: true }).fill(phone);
  await page.getByLabel("Пароль", { exact: true }).fill(password);
  await page.locator(".auth-form > button.button").click();
  await page.waitForURL(base + "/cabinet", { timeout: 3000 });
  check(await page.locator(".preparation-screen").count() === 0, "Login repeats preparation");
  await page.getByRole("button", { name: "Выйти", exact: true }).click();
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.goto(base + "/");
  check(await page.locator(".finance-theatre").getAttribute("data-playing") === "false", "Reduced motion still cycles");
  check(await page.locator(".finance-core").evaluate(el => getComputedStyle(el).animationName) === "none", "Reduced motion animates core");
  check(await page.locator(".journey-step").first().evaluate(el => getComputedStyle(el).opacity) === "1", "Reduced motion hides content");
  // Reuse authenticated setup only in temporary DB to test skip and failure recovery.
  await page.request.post(base + "/api/auth/login", { data: { phone, password } });
  await page.evaluate(() => sessionStorage.setItem("alfa-cabinet-preparation", String(Date.now())));
  await page.goto(base + "/onboarding");
  await page.waitForURL(base + "/cabinet", { timeout: 3000 });
  await page.emulateMedia({ reducedMotion: "no-preference" });
  await page.evaluate(() => sessionStorage.setItem("alfa-cabinet-preparation", String(Date.now())));
  await page.goto(base + "/onboarding");
  await page.getByRole("progressbar").waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForFunction(() => Number(document.querySelector(".preparation-sphere")?.getAttribute("aria-valuenow")) >= 10);
  await page.screenshot({ path: "output/playwright/motion-preparation-mobile.png" });
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "Preparation overflow");
  await page.route("**/api/config", route => route.abort());
  await page.getByRole("button", { name: "Перейти сразу" }).click();
  await page.getByRole("alert").filter({ hasText: "Профиль создан" }).waitFor();
  await page.unroute("**/api/config");
  await page.getByRole("button", { name: "Повторить открытие" }).click();
  await page.waitForURL(base + "/cabinet", { timeout: 3000 });
  check(errors.length === 0, "Runtime errors: " + errors.join(", "));
}
